-- V2.5.93 operator notification email admin + manual override review checkpoint

create table if not exists public.resident_email_admin_audit (
  id bigint generated by default as identity primary key,
  initials text not null references public.resident_directory(initials),
  old_email text not null default '',
  new_email text not null,
  source text not null default 'manual',
  actor_user_id uuid not null,
  actor_initials text not null,
  created_at timestamptz not null default now()
);

alter table public.resident_email_admin_audit enable row level security;
drop policy if exists "email admin operator read" on public.resident_email_admin_audit;
create policy "email admin operator read" on public.resident_email_admin_audit
for select to authenticated using (public.is_lifecycle_operator_v2592(auth.uid()));

grant select on public.resident_email_admin_audit to authenticated;

create or replace function public.set_resident_notification_email_v2593(
  p_initials text, p_email text
) returns jsonb
language plpgsql security definer
set search_path to 'public','auth'
as $$
declare v_actor text; v_old text; v_email text:=lower(trim(coalesce(p_email,'')));
begin
  if not public.is_lifecycle_operator_v2592(auth.uid()) then raise exception 'LIFECYCLE_OPERATOR_REQUIRED'; end if;
  select initials into v_actor from public.user_profiles where user_id=auth.uid() and approved=true limit 1;
  if v_actor is null then raise exception 'APPROVED_PROFILE_REQUIRED'; end if;
  if not exists(select 1 from public.resident_directory where initials=p_initials and active=true) then raise exception 'UNKNOWN_OR_INACTIVE_RESIDENT'; end if;
  if v_email='' or v_email !~ '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$' then raise exception 'INVALID_EMAIL'; end if;
  select coalesce(email,'') into v_old from public.account_settings where initials=p_initials for update;
  if not found then raise exception 'ACCOUNT_SETTINGS_NOT_FOUND'; end if;
  update public.account_settings set email=v_email,updated_at=now() where initials=p_initials;
  insert into public.resident_email_admin_audit(initials,old_email,new_email,source,actor_user_id,actor_initials)
  values(p_initials,coalesce(v_old,''),v_email,'manual',auth.uid(),v_actor);
  return jsonb_build_object('ok',true,'initials',p_initials,'email',v_email,'actor',v_actor);
end $$;

grant execute on function public.set_resident_notification_email_v2593(text,text) to authenticated;

create or replace function public.autofill_notification_emails_v2593()
returns jsonb
language plpgsql security definer
set search_path to 'public','auth'
as $$
declare v_actor text; r record; v_count int:=0;
begin
  if not public.is_lifecycle_operator_v2592(auth.uid()) then raise exception 'LIFECYCLE_OPERATOR_REQUIRED'; end if;
  select initials into v_actor from public.user_profiles where user_id=auth.uid() and approved=true limit 1;
  if v_actor is null then raise exception 'APPROVED_PROFILE_REQUIRED'; end if;
  for r in
    select a.initials,coalesce(a.email,'') old_email,
           lower(trim(coalesce(nullif(up.email,''),au.email,''))) login_email
    from public.account_settings a
    join public.resident_directory rd on rd.initials=a.initials and rd.active=true
    left join public.user_profiles up on up.initials=a.initials and up.approved=true
    left join auth.users au on au.id=up.user_id
    where coalesce(trim(a.email),'')=''
  loop
    if r.login_email<>'' and r.login_email ~ '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$' then
      update public.account_settings set email=r.login_email,updated_at=now() where initials=r.initials;
      insert into public.resident_email_admin_audit(initials,old_email,new_email,source,actor_user_id,actor_initials)
      values(r.initials,r.old_email,r.login_email,'login_autofill',auth.uid(),v_actor);
      v_count:=v_count+1;
    end if;
  end loop;
  return jsonb_build_object('ok',true,'filled',v_count,'actor',v_actor);
end $$;

grant execute on function public.autofill_notification_emails_v2593() to authenticated;


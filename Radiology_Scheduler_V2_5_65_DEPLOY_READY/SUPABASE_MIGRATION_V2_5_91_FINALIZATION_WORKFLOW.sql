-- Reset integration: clear lifecycle/late grants before FINAL; never erase an administration FINAL.
create or replace function public.reset_month_schedule_v2522(p_year integer, p_month integer)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_uid uuid:=auth.uid(); v_initials text; v_is_senior boolean:=false; v_backup_ids bigint[]; v_cover_events integer:=0;
  v_schedules integer:=0; v_backups integer:=0; v_swaps integer:=0; v_backup_swaps integer:=0; v_repairs integer:=0; v_fairness integer:=0; v_lifecycle integer:=0; v_late integer:=0;
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED'; end if;
  select up.initials into v_initials from public.user_profiles up where up.user_id=v_uid and up.approved=true limit 1;
  if v_initials is null then raise exception 'APPROVED_PROFILE_REQUIRED'; end if;
  select public.is_senior(v_uid) into v_is_senior;
  if not v_is_senior then raise exception 'SENIOR_ONLY'; end if;
  if p_year<2026 or p_month<1 or p_month>12 then raise exception 'INVALID_MONTH'; end if;
  if exists(select 1 from public.schedule_lifecycle where year=p_year and month=p_month and state='final') then raise exception 'RESET_BLOCKED_FINAL_SCHEDULE'; end if;
  select coalesce(array_agg(id),array[]::bigint[]) into v_backup_ids from public.backup_assignments where year=p_year and month=p_month;
  if coalesce(array_length(v_backup_ids,1),0)>0 then select count(*) into v_cover_events from public.backup_cover_events where backup_id=any(v_backup_ids); end if;
  if v_cover_events>0 then raise exception 'RESET_BLOCKED_COMPLETED_BACKUP_ACTIVITY'; end if;
  delete from public.late_swap_access where year=p_year and month=p_month; get diagnostics v_late=row_count;
  delete from public.schedule_lifecycle where year=p_year and month=p_month; get diagnostics v_lifecycle=row_count;
  delete from public.schedule_repairs where year=p_year and month=p_month; get diagnostics v_repairs=row_count;
  delete from public.backup_swap_requests where year=p_year and month=p_month; get diagnostics v_backup_swaps=row_count;
  delete from public.swap_requests where year=p_year and month=p_month; get diagnostics v_swaps=row_count;
  delete from public.backup_assignments where year=p_year and month=p_month; get diagnostics v_backups=row_count;
  delete from public.fairness_history where year=p_year and month=p_month; get diagnostics v_fairness=row_count;
  delete from public.schedules where year=p_year and month=p_month; get diagnostics v_schedules=row_count;
  return jsonb_build_object('ok',true,'year',p_year,'month',p_month,'reset_by',v_initials,'schedules_deleted',v_schedules,'backups_deleted',v_backups,'swap_requests_deleted',v_swaps,'backup_swap_requests_deleted',v_backup_swaps,'repairs_deleted',v_repairs,'fairness_rows_deleted',v_fairness,'lifecycle_deleted',v_lifecycle,'late_access_deleted',v_late,'preferences_preserved',true,'recurring_preferences_preserved',true,'credit_redemptions_preserved',true);
end;
$$;

-- V2.5.128 — privatus SP + ŠR planavimo sluoksnis.
-- Šios eilutės sąmoningai NEPATEKIA į viešą rezidentų pageidavimų auditą,
-- taisyklių langą, Excel eksportą ar pristatymo vadovą.
-- Detales gali matyti tik patvirtintos SP ir ŠR paskyros.

create table if not exists public.operator_private_pair_preferences_v25128 (
  id bigint generated by default as identity primary key,
  owner_initials text not null references public.resident_directory(initials) on delete cascade,
  year integer not null,
  month integer not null check (month between 1 and 12),
  preference_type text not null check (preference_type in ('together','apart')),
  target_initials text not null references public.resident_directory(initials) on delete cascade,
  scope_type text not null check (scope_type in ('month','week','day')),
  scope_start_date date null,
  block text not null default 'ANY' check (block in ('ANY','AM','PM')),
  workplace text not null default 'ANY' check (workplace in ('ANY','CENTRO RO','Onko RO','SPS RO','Centro UG','SPS UG','ADC 144','ADC 145','Vaikų UG','Mamografijos')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (owner_initials in ('SP','ŠR')),
  check (target_initials <> owner_initials),
  check (
    (scope_type='month' and scope_start_date is null)
    or (scope_type in ('week','day') and scope_start_date is not null)
  )
);

create index if not exists idx_operator_private_pair_month_v25128
  on public.operator_private_pair_preferences_v25128(year,month,owner_initials);

create unique index if not exists operator_private_pair_unique_v25128
on public.operator_private_pair_preferences_v25128(
  owner_initials,year,month,preference_type,target_initials,scope_type,
  coalesce(scope_start_date,date '1900-01-01'),block,workplace
);

create table if not exists public.operator_private_pair_preference_audit_v25128 (
  id bigint generated by default as identity primary key,
  year integer not null,
  month integer not null,
  actor_user_id uuid null,
  actor_initials text not null,
  owner_initials text not null,
  action text not null check (action in ('create','delete')),
  preference_id bigint null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- Perkelti ankstesnius SP privačius pageidavimus, jei V2.5.123 jau buvo paleista.
do $$
begin
  if to_regclass('public.sp_private_pair_preferences_v25123') is not null then
    insert into public.operator_private_pair_preferences_v25128(
      owner_initials,year,month,preference_type,target_initials,scope_type,scope_start_date,block,workplace,created_at,updated_at
    )
    select
      'SP',year,month,preference_type,target_initials,scope_type,scope_start_date,block,workplace,created_at,updated_at
    from public.sp_private_pair_preferences_v25123
    on conflict do nothing;
  end if;
end $$;


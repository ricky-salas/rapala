-- Target resident accepts a backup swap, but this intentionally DOES NOT mutate
-- backup_assignments. ACTUAL changes only after SR approves.
create or replace function public.accept_backup_swap_participant_v25111(p_request_id bigint)
returns public.backup_swap_requests
language plpgsql security definer set search_path=public,auth as $$
declare r public.backup_swap_requests%rowtype; v_uid uuid:=auth.uid(); v_initials text;
begin
  select initials into v_initials from public.user_profiles where user_id=v_uid and approved=true limit 1;
  select * into r from public.backup_swap_requests where id=p_request_id for update;
  if not found then raise exception 'BACKUP_SWAP_NOT_FOUND'; end if;
  if r.status<>'pending' then raise exception 'BACKUP_SWAP_NOT_PENDING'; end if;
  if v_initials is distinct from r.target then raise exception 'BACKUP_SWAP_ACCEPT_NOT_AUTHORIZED' using errcode='42501'; end if;
  update public.backup_swap_requests
     set participant_accepted_at=now(), participant_accepted_by=v_uid
   where id=r.id returning * into r;
  return r;
end $$;

-- SR must be the exact operational leader account, not a generic admin/researcher.
create or replace function public.approve_backup_swap_by_sr_v25111(p_request_id bigint)
returns public.backup_swap_requests
language plpgsql security definer set search_path=public,auth as $$
declare r public.backup_swap_requests%rowtype; v_uid uuid:=auth.uid(); v_initials text;
begin
  select initials into v_initials from public.user_profiles where user_id=v_uid and approved=true limit 1;
  if v_initials is distinct from 'SR' then raise exception 'SR_ONLY' using errcode='42501'; end if;
  select * into r from public.backup_swap_requests where id=p_request_id for update;
  if not found then raise exception 'BACKUP_SWAP_NOT_FOUND'; end if;
  if r.status<>'pending' then raise exception 'BACKUP_SWAP_NOT_PENDING'; end if;
  if r.participant_accepted_at is null then raise exception 'BOTH_RESIDENTS_NOT_CONSENTED'; end if;
  perform public.accept_backup_swap(p_request_id);
  update public.backup_swap_requests
     set senior_decision='approved',senior_decided_at=now(),senior_decided_by=v_uid
   where id=p_request_id returning * into r;
  return r;
end $$;

create or replace function public.reject_backup_swap_by_sr_v25111(p_request_id bigint)
returns public.backup_swap_requests
language plpgsql security definer set search_path=public,auth as $$
declare r public.backup_swap_requests%rowtype; v_uid uuid:=auth.uid(); v_initials text;
begin
  select initials into v_initials from public.user_profiles where user_id=v_uid and approved=true limit 1;
  if v_initials is distinct from 'SR' then raise exception 'SR_ONLY' using errcode='42501'; end if;
  select * into r from public.backup_swap_requests where id=p_request_id for update;
  if not found then raise exception 'BACKUP_SWAP_NOT_FOUND'; end if;
  if r.status<>'pending' then raise exception 'BACKUP_SWAP_NOT_PENDING'; end if;
  update public.backup_swap_requests
     set status='rejected',responded_at=now(),senior_decision='declined',senior_decided_at=now(),senior_decided_by=v_uid
   where id=r.id returning * into r;
  return r;
end $$;

create or replace function public.mark_normal_swap_sr_decision_v25111(p_request_id bigint,p_decision text)
returns public.swap_requests
language plpgsql security definer set search_path=public,auth as $$
declare r public.swap_requests%rowtype; v_uid uuid:=auth.uid(); v_initials text; v_dec text:=lower(trim(coalesce(p_decision,'')));
begin
  select initials into v_initials from public.user_profiles where user_id=v_uid and approved=true limit 1;
  if v_initials is distinct from 'SR' then raise exception 'SR_ONLY' using errcode='42501'; end if;
  if v_dec not in ('approved','declined') then raise exception 'INVALID_SR_DECISION'; end if;
  select * into r from public.swap_requests where id=p_request_id for update;
  if not found then raise exception 'SWAP_NOT_FOUND'; end if;
  if v_dec='declined' then
    if r.status<>'approved' then raise exception 'RESIDENT_CONSENT_NOT_COMPLETE'; end if;
    update public.swap_requests set status='rejected',senior_decision='declined',senior_decided_at=now(),senior_decided_by=v_uid
      where id=r.id returning * into r;
  else
    if r.status<>'approved' then raise exception 'SWAP_NOT_APPROVED_BY_RESIDENTS'; end if;
    update public.swap_requests set senior_decision='approved',senior_decided_at=now(),senior_decided_by=v_uid
      where id=r.id returning * into r;
  end if;
  return r;
end $$;


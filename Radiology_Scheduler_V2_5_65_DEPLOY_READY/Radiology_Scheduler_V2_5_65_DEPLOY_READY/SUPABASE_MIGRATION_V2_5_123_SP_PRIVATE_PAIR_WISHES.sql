-- V2.5.123 — SP private privileged pair wishes.
-- Intentionally isolated from ordinary resident preferences and public audit tables.

create table if not exists public.sp_private_pair_preferences_v25123 (
  id bigint generated by default as identity primary key,
  year integer not null,
  month integer not null check (month between 1 and 12),
  preference_type text not null check (preference_type in ('together','apart')),
  target_initials text not null references public.resident_directory(initials) on delete cascade,
  scope_type text not null check (scope_type in ('month','week','day')),
  scope_start_date date null,
  block text not null default 'ANY' check (block in ('ANY','AM','PM')),
  workplace text not null default 'ANY' check (workplace in ('ANY','CENTRO RO','Onko RO','SPS RO','Centro UG','SPS UG','ADC 144','ADC 145','Vaikų UG','Mamografijos')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (target_initials <> 'SP'),
  check (
    (scope_type='month' and scope_start_date is null)
    or (scope_type in ('week','day') and scope_start_date is not null)
  )
);

create index if not exists idx_sp_private_pair_preferences_month_v25123
  on public.sp_private_pair_preferences_v25123(year,month);

create table if not exists public.sp_private_pair_preference_audit_v25123 (
  id bigint generated by default as identity primary key,
  year integer not null,
  month integer not null,
  actor_user_id uuid null,
  actor_initials text not null,
  action text not null check (action in ('create','delete')),
  preference_id bigint null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.sp_private_pair_preferences_v25123 enable row level security;
alter table public.sp_private_pair_preference_audit_v25123 enable row level security;

